export type AiExamType =
  | 'OGE_SUMMARY'
  | 'OGE_ESSAY'
  | 'EGE_ESSAY'
  | 'FINAL_ESSAY';

export interface AiGradingPayload {
  examType: AiExamType;
  promptText: string;
  sourceText?: string;
  studentText: string;
}

export interface AiCriterionScore {
  code: string;
  title: string;
  score: number;
  maxScore: number;
  comment: string;
  /** Used by pass/fail rubrics such as Итоговое сочинение (FINAL_ESSAY) */
  passed?: boolean;
  statusLabel?: 'Зачёт' | 'Незачёт';
}

export interface AiRequirementCheck {
  code: string;
  title: string;
  passed: boolean;
  statusLabel: 'Зачёт' | 'Незачёт';
  comment: string;
}

export interface AiGradingReport {
  isDemo: boolean;
  totalScore: number;
  maxTotalScore: number;
  verdictLabel: string;
  isPassFail?: boolean;
  overallPassed?: boolean;
  requirements?: AiRequirementCheck[];
  rubricNote?: string;
  criteria: AiCriterionScore[];
  strengths: string[];
  improvements: string[];
}

