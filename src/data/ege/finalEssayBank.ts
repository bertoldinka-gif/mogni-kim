export function generateFinalEssaySet(): FinalEssayTopic[] {
  const pickTwo = (sec: 1 | 2 | 3): FinalEssayTopic[] => {
    const pool = FINAL_ESSAY_TOPICS.filter((t) => t.section === sec);
    const shuffled = [...pool].sort(() => Math.random() - 0.5);
    return shuffled.slice(0, 2);
  };
  return [...pickTwo(1), ...pickTwo(2), ...pickTwo(3)];
}
