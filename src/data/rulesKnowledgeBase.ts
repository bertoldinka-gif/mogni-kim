function normalizeQuery(raw: string): string {
  return raw
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^а-яa-z0-9\s-]/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * 100% local keyword/stem matching against RULES_KNOWLEDGE_BASE.
 * Returns the best matching rule or null if nothing matched.
 */
export function findMatchingRule(query: string): RuleKnowledgeEntry | null {
  const norm = normalizeQuery(query);
  if (!norm) return null;

  const tokens = norm.split(' ').filter((t) => t.length >= 2);
  let bestEntry: RuleKnowledgeEntry | null = null;
  let bestScore = 0;

  for (const entry of RULES_KNOWLEDGE_BASE) {
    let score = 0;
    const normTitle = normalizeQuery(entry.topicTitle);

    for (const kw of entry.keywords) {
      const normKw = normalizeQuery(kw);
      if (norm === normKw) {
        score += 12;
      } else if (norm.includes(normKw)) {
        score += 6 + Math.min(4, Math.floor(normKw.length / 3));
      } else {
        for (const token of tokens) {
          const stem = token.length >= 5 ? token.slice(0, -1) : token;
          if (normKw.includes(stem) || stem.includes(normKw)) {
            score += 3;
          }
        }
      }
    }

    for (const token of tokens) {
      const stem = token.length >= 5 ? token.slice(0, -1) : token;
      if (normTitle.includes(stem)) {
        score += 4;
      }
    }

    if (score > bestScore) {
      bestScore = score;
      bestEntry = entry;
    }
  }

  return bestScore > 0 ? bestEntry : null;
}
