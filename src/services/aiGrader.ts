export async function evaluateEssayWithAI(
  payload: AiGradingPayload
): Promise<AiGradingReport> {
  if (AI_PROXY_ENDPOINT.trim()) {
    const response = await fetch(AI_PROXY_ENDPOINT, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(payload),
    });

    if (!response.ok) {
      throw new Error(`Ошибка сервера проверки: ${response.status}`);
    }

    return (await response.json()) as AiGradingReport;
  }

  await new Promise((resolve) => setTimeout(resolve, 1500));
  return buildDemoReport(payload);
}
