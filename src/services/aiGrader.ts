export function countEssayWords(text: string): number {
  const trimmed = text.trim();
  if (!trimmed) return 0;
  return trimmed
    .split(/\s+/)
    .filter((token) => /[а-яА-ЯёЁa-zA-Z0-9]/.test(token)).length;
}

const FORBIDDEN_POP_CULTURE_REGEX =
  /(комикс|аниме|манг[аеуи]|фанфик|видеоигр|компьютерн\w+\s+игр)/i;

