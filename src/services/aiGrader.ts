export function buildExternalAiPrompt(payload: AiGradingPayload): string {
  const words = countEssayWords(payload.studentText);
  const minWords = MIN_WORDS_BY_EXAM[payload.examType];

  const lines = [
    `Проверь, пожалуйста, мою письменную работу по русскому языку (${EXAM_TITLES[payload.examType]}) строго по актуальным критериям ФИПИ.`,
    '',
    `ЗАДАНИЕ: ${payload.promptText}`,
  ];

  if (payload.sourceText) {
    lines.push('', 'ИСХОДНЫЙ ТЕКСТ:', payload.sourceText);
  }

  lines.push(
    '',
    `МОЯ РАБОТА (${words} слов; минимальный порог: ${minWords} слов):`,
    payload.studentText.trim() || '[Черновик ещё не заполнен]',
    '',
    getOfficialRubricInstructions(payload.examType),
    '',
    payload.examType === 'FINAL_ESSAY'
      ? 'Выведи вердикт по Требованиям 1 и 2, статус «Зачёт / Незачёт» по каждому критерию К1–К5, итоговый результат («ЗАЧЁТ» или «НЕЗАЧЁТ»), посчитай плотность ошибок на 100 слов, выпиши ошибки с исправлением и дай конкретные советы по доработке.'
      : 'Выведи таблицу баллов по каждому критерию, общий итог, выпиши все орфографические, пунктуационные, грамматические, речевые, логические и фактические ошибки с исправлением и дай конкретные советы по улучшению.'
  );

  return lines.join('\n');
}

